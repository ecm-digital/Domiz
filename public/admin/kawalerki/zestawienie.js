const SORTERS = {
  kolejnosc: (a, b) => a.kolejnosc - b.kolejnosc,
  cena: (a, b) => (a.cena ?? Infinity) - (b.cena ?? Infinity),
  m2: (a, b) => (a.m2 ?? -1) - (b.m2 ?? -1),
  ogrod: (a, b) => (a.ogrod ?? -1) - (b.ogrod ?? -1),
  zl: (a, b) => (cenaZaM2(a.cena, a.m2) ?? Infinity) - (cenaZaM2(b.cena, b.m2) ?? Infinity),
  suma: (a, b) => (a.suma ?? Infinity) - (b.suma ?? Infinity),
  nazwa: (a, b) => a.nazwa.localeCompare(b.nazwa, 'pl'),
};

export function filterUnits(state) {
  const q = (state.q || '').trim().toLowerCase();
  const list = UNITS.filter((u) => {
    if (state.tor && state.tor !== 'wszystkie' && u.tor !== state.tor) return false;
    if (state.dev && u.dev !== state.dev) return false;
    if (state.dzielnica && u.dzielnica !== state.dzielnica) return false;
    if (state.inwestycja && u.inwestycja !== state.inwestycja) return false;
    if (state.pokoje && String(u.pokoje) !== String(state.pokoje)) return false;
    if (state.status && u.dostepnosc !== state.status) return false;
    if (state.ogrod && u.ogrodBucket !== state.ogrod) return false;
    if (state.budzet && budzetKlasa(u) !== state.budzet) return false;
    if (q) {
      const hay = `${u.id} ${u.nazwa} ${u.lokal} ${u.inwestycja} ${u.dev} ${u.dzielnica}`.toLowerCase();
      if (!hay.includes(q)) return false;
    }
    return true;
  });
  const cmp = SORTERS[state.sort] || SORTERS.kolejnosc;
  const dir = state.dir === -1 ? -1 : 1;
  return list.sort((a, b) => cmp(a, b) * dir);
}

export function unique(key) {
  return [...new Set(UNITS.map((u) => u[key]).filter(Boolean))].sort((a, b) => String(a).localeCompare(String(b), 'pl'));
}
